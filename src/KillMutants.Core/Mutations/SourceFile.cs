using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace KillMutants.Mutations;

/// <summary>Answers questions about where a syntax tree came from.</summary>
internal static class SourceFile
{
    private static readonly string[] GeneratedSuffixes =
    [
        // Source generators, and the XAML and Razor compilers.
        ".g.cs",
        ".g.i.cs",

        // The Windows Forms and resx designers, which is the case Stryker.NET recognises by name.
        ".designer.cs",
    ];

    /// <summary>
    /// True when a file is machine-written, and so no business of a mutation run.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Mutating generated code reports findings against something the developer cannot fix: the
    /// answer to "this mutant survived" is to change a template, a schema or a generator, and often
    /// none of those are theirs. It also buries the real findings under hundreds of them.
    /// </para>
    /// <para>
    /// Two rules, and the second is the one that matters. Names and directories only catch what we
    /// have thought of - <c>obj</c> misses a project with a custom
    /// <c>BaseIntermediateOutputPath</c>, and a suffix list misses whatever the next generator
    /// chooses to call its output. The <c>&lt;auto-generated&gt;</c> header travels <em>with</em> the
    /// file instead, which is why the convention exists: the C# compiler itself reads it to suppress
    /// analyser warnings, and T4, protobuf, the designers, XSD and EF all emit it. Recognising it is
    /// what closes RB-008.
    /// </para>
    /// <para>
    /// The header is only honoured at the very top of the file, before any code, exactly as the
    /// convention specifies. A comment further down is a comment.
    /// </para>
    /// </remarks>
    public static bool IsGenerated(SyntaxTree tree)
    {
        ArgumentNullException.ThrowIfNull(tree);

        return HasGeneratedPath(tree.FilePath) || HasGeneratedHeader(tree);
    }

    private static bool HasGeneratedPath(string path)
    {
        if (string.IsNullOrEmpty(path))
        {
            return false;
        }

        if (GeneratedSuffixes.Any(suffix => path.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        string separator = Path.DirectorySeparatorChar.ToString();

        return path.Contains(separator + "obj" + separator, StringComparison.OrdinalIgnoreCase);
    }

    private static bool HasGeneratedHeader(SyntaxTree tree)
    {
        SyntaxNode root = tree.GetRoot();
        SyntaxToken first = root.GetFirstToken(includeZeroWidth: true);

        SyntaxTriviaList leading = first.HasLeadingTrivia
            ? first.LeadingTrivia
            : ((CompilationUnitSyntax)root).EndOfFileToken.LeadingTrivia;

        return leading
            .Where(trivia => trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) ||
                             trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
            .Any(trivia => trivia.ToString() is var text &&
                           (text.Contains("<auto-generated", StringComparison.Ordinal) ||
                            text.Contains("<autogenerated", StringComparison.Ordinal)));
    }
}
