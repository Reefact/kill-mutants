namespace KillMutants.Coverage;

/// <summary>
/// The source of the recorder compiled into the assembly under test during the coverage pass.
/// </summary>
/// <remarks>
/// <para>
/// Deliberately written in conservative C#: no file-scoped namespace, no collection expressions, no
/// LINQ. It is compiled into the <em>user's</em> project, whose language version we do not control.
/// </para>
/// <para>
/// <c>Hit</c> returns its argument, so wrapping an expression in it cannot change what that
/// expression evaluates to, nor when. That is the whole reason this instrumentation needs none of
/// the machinery a mutation switch would: there is no branch to place, so no context in which the
/// placement is illegal, and therefore no rollback.
/// </para>
/// </remarks>
internal static class CoverageProbe
{
    /// <summary>The fully qualified name of the generated recorder's <c>Hit</c> method.</summary>
    public const string HitMethod = "global::KillMutantsGenerated.CoverageProbe.Hit";

    /// <summary>The environment variable naming the file the recorder writes to.</summary>
    public const string OutputPathVariable = "KILLMUTANTS_COVERAGE_FILE";

    /// <summary>The recorder's source.</summary>
    public static string Source { get; } =
        """
        // <auto-generated> Added by KillMutants for the coverage pass only. </auto-generated>
        namespace KillMutantsGenerated
        {
            internal static class CoverageProbe
            {
                private static readonly System.Collections.Generic.HashSet<int> Hits =
                    new System.Collections.Generic.HashSet<int>();

                static CoverageProbe()
                {
                    System.AppDomain.CurrentDomain.ProcessExit += delegate { Flush(); };
                }

                public static T Hit<T>(int id, T value)
                {
                    lock (Hits) { Hits.Add(id); }

                    return value;
                }

                private static void Flush()
                {
                    string path = System.Environment.GetEnvironmentVariable("KILLMUTANTS_COVERAGE_FILE");

                    if (string.IsNullOrEmpty(path)) { return; }

                    var builder = new System.Text.StringBuilder();

                    lock (Hits)
                    {
                        foreach (int id in Hits) { builder.Append(id).Append('\n'); }
                    }

                    System.IO.File.WriteAllText(path, builder.ToString());
                }
            }
        }
        """;
}
