using KillMutants.Mutations;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace KillMutants.Core.Tests.Mutations;

/// <summary>
/// Closes RB-008. Mutating generated code reports findings the developer cannot act on - the fix is
/// in a template, a schema or somebody else's generator - and buries the real findings under them.
/// </summary>
public class SourceFileTests
{
    private const string Code = "class C { bool M(int a) => a >= 18; }";

    [Theory]
    [InlineData("/src/Model.g.cs")]
    [InlineData("/src/Page.g.i.cs")]
    [InlineData("/src/Form.Designer.cs")]
    [InlineData("/src/Form.designer.cs")]
    [InlineData("/src/obj/Debug/net10.0/Assembly.cs")]
    public void A_path_that_names_generated_output_is_recognised(string path)
    {
        Assert.True(SourceFile.IsGenerated(Tree(Code, path)));
    }

    /// <summary>
    /// The same rule read through the platform's own separator, which on Windows is the other
    /// character entirely.
    /// </summary>
    /// <remarks>
    /// Built at runtime rather than written down: writing a backslash path here would assert
    /// something false on Unix, where a backslash is an ordinary character in a file name and
    /// <c>\src\obj\x.cs</c> is one file with a strange name, not a file in an <c>obj</c>
    /// directory. On a Windows runner this is the case the rule used to miss.
    /// </remarks>
    [Fact]
    public void A_path_written_with_the_platform_separator_is_recognised_too()
    {
        char separator = Path.DirectorySeparatorChar;

        Assert.True(SourceFile.IsGenerated(
            Tree(Code, $"{separator}src{separator}obj{separator}Debug{separator}Assembly.cs")));
    }

    [Theory]
    [InlineData("/src/Model.cs")]
    [InlineData("/src/Gadget.cs")]
    // "obj" has to be a directory of its own, not a fragment of a name
    [InlineData("/src/object-model/Model.cs")]
    [InlineData("/src/MyObj/Model.cs")]
    public void An_ordinary_path_is_not(string path)
    {
        Assert.False(SourceFile.IsGenerated(Tree(Code, path)));
    }

    /// <summary>
    /// The rule that closes the entry. A name-and-directory rule only catches what we thought of:
    /// it misses a project with a custom BaseIntermediateOutputPath, and whatever the next generator
    /// decides to call its output. The header travels with the file.
    /// </summary>
    [Theory]
    [InlineData("// <auto-generated/>")]
    [InlineData("// <auto-generated>\n//     This file was generated by a tool.\n// </auto-generated>")]
    [InlineData("//------\n// <autogenerated>\n//------")]
    [InlineData("/* <auto-generated> by protoc */")]
    public void A_file_that_declares_itself_generated_is_recognised_wherever_it_lives(string header)
    {
        // Deliberately outside obj, with an ordinary name: only the header says what it is.
        Assert.True(SourceFile.IsGenerated(Tree($"{header}\n{Code}", "/src/artifacts/Model.cs")));
    }

    /// <summary>
    /// The convention puts the marker at the top of the file, before any code. Honouring it further
    /// down would let a comment about generated code silence a whole file of hand-written code.
    /// </summary>
    [Fact]
    public void The_header_only_counts_at_the_top_of_the_file()
    {
        Assert.False(SourceFile.IsGenerated(
            Tree($"using System;\n\n// <auto-generated/>\n{Code}", "/src/Model.cs")));
    }

    [Fact]
    public void A_file_with_no_path_at_all_is_judged_on_its_content()
    {
        Assert.False(SourceFile.IsGenerated(Tree(Code, string.Empty)));
        Assert.True(SourceFile.IsGenerated(Tree($"// <auto-generated/>\n{Code}", string.Empty)));
    }

    /// <summary>An empty generated file must not throw on the way to being skipped.</summary>
    [Fact]
    public void A_file_containing_only_a_header_is_still_recognised()
    {
        Assert.True(SourceFile.IsGenerated(Tree("// <auto-generated/>\n", "/src/Empty.cs")));
    }

    private static SyntaxTree Tree(string source, string path) =>
        CSharpSyntaxTree.ParseText(source, path: path);
}
